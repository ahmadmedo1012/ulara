#!/usr/bin/env node
/**
 * gen-wrappers.mjs — r359 A2: emit the 44 web contract seats
 * `frontend/src/components/illustrations/r359/<key>.tsx`.
 *
 * The wrappers are 100% GENERATED (never hand-edit): each is a thin
 * default-exported React component binding the shared-art builder for
 * its key to the web renderer (lib/runtime.tsx). GRADUATION maps a
 * key to its family scene module once that family lands its final
 * drawings; unlisted keys still point at the M0 stubs.
 *
 * Run from the repo root:  node scripts/art/gen-wrappers.mjs
 */
import { build } from 'esbuild';
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');
const OUT_DIR = join(ROOT, 'frontend', 'src', 'components', 'illustrations', 'r359');

/* key → family scene module (relative to shared/art). Update as
 * families graduate; a key not listed here rides the stubs. */
const GRADUATED = {
  // 'hero-elevation': 'scenes/hero',
};

/* ── bundle the manifest to read ART_KEYS as JSON ────────────────── */
const TMP = join(ROOT, '.tmp-art-manifest.mjs');
await build({
  entryPoints: [join(ROOT, 'shared', 'art', 'manifest.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  outfile: TMP,
  logLevel: 'silent',
});
const { ART_KEYS } = await import(`file://${TMP}`);
rmSync(TMP, { force: true });

mkdirSync(OUT_DIR, { recursive: true });

let n = 0;
for (const meta of ART_KEYS) {
  const mod = GRADUATED[meta.key];
  const importLine = mod
    ? `import { sceneFor } from '@shared/art/${mod}';`
    : `import { stubFor } from '@shared/art/scenes/stubs';`;
  const accessor = mod
    ? `sceneFor('${meta.key}')`
    : `stubFor('${meta.key}')`;
  const body = `/**
 * r359 art key \`${meta.key}\` — ${meta.title}
 * GENERATED by scripts/art/gen-wrappers.mjs (A2) — do not hand-edit.
 * The drawing lives in shared/art (grammar + scenes); this file is
 * the web contract seat: default export, lazy-chunkable, token-colored.
 */
import { ArtSvg } from './lib/runtime';
${importLine}

export interface R359ArtProps {
  className?: string;
  title?: string;
  animated?: boolean;
  theme?: 'light' | 'dark';
}

const BUILDER = ${accessor};

export default function ${meta.pascal}(props: R359ArtProps): React.JSX.Element {
  return <ArtSvg build={BUILDER} {...props} />;
}
`;
  writeFileSync(join(OUT_DIR, `${meta.key}.tsx`), body);
  n++;
}
console.log(`gen-wrappers: ${n} wrappers → ${OUT_DIR}`);
