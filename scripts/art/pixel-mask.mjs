/**
 * r344 A1 — the pixel-mask sprite generator (OUR OWN grain).
 *
 * The pixel-dissolve CTA fill walks a 20-slice dithered mask 0%→100%
 * in steps(19, end): a temporal density dissolve (direction-neutral,
 * RTL-safe). This script deterministically renders that sprite —
 * re-runs are byte-identical (fixed LCG seed), so the artifact in
 * public/media/brand/pixel-mask.svg always has provenance here.
 *
 * Our grain (deliberately NOT the retired reference's): 4px cells on
 * a 10×10 cell slice (40×40 units), 20 slices in a 800×40 viewBox,
 * coverage ramping slice0=0% (rest: fill fully hidden) → slice19=100%
 * (hover: the slab fully seated). White cell = mask-visible (the
 * luminance default).
 *
 * Usage: node scripts/art/pixel-mask.mjs   (writes the artifact)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(ROOT, '../../frontend/public/brand/pixel-mask.svg');

const SLICES = 20;
const COLS = 10;
const ROWS = 10;
const CELL = 4; // 40×40 units per slice → 800×40 viewBox
const SEED = 344; // the round number — the dither's fixed fingerprint

/** Deterministic LCG — the same seed always paints the same dither. */
function lcg(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 0x100000000;
  };
}

const rects = [];
for (let slice = 0; slice < SLICES; slice++) {
  // slice0 = 0% (rest), slice19 = 100% (seated) — linear density ramp.
  const coverage = slice / (SLICES - 1);
  if (coverage === 0) continue;
  const rand = lcg(SEED * 7919 + slice * 104729);
  for (let row = 0; row < ROWS; row++) {
    for (let col = 0; col < COLS; col++) {
      if (rand() >= coverage) continue;
      const x = slice * COLS * CELL + col * CELL; // each slice = 40 units
      const y = row * CELL;
      rects.push(`<rect x="${x}" y="${y}" width="${CELL}" height="${CELL}"/>`);
    }
  }
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 40" width="800" height="40" shape-rendering="crispEdges" fill="#fff"><!-- r344 pixel-dissolve mask — generated by scripts/art/pixel-mask.mjs (seed ${SEED}, 20 slices × ${COLS}×${ROWS} @ ${CELL}px) --><g>${rects.join('')}</g></svg>\n`;
writeFileSync(OUT, svg);
const count = (svg.match(/<rect/g) || []).length;
console.log(`pixel-mask.svg written: ${SLICES} slices, ${count} cells, ${(svg.length / 1024).toFixed(1)}KB`);
