#!/usr/bin/env node
/**
 * build-native.mjs — r359 A2: generate the mobile art library.
 *
 * Copies the pure-TS art source (shared/art: grammar + scenes +
 * manifest) into apps/mobile/src/components/art/shared/ VERBATIM
 * (the directory structure preserves every relative import), then
 * emits the React-Native renderer (RnArt.tsx) + one wrapper per key
 * + index.ts (PascalCase re-exports).
 *
 * The RN renderer swaps the grammar's CSS-var palette for concrete
 * hex per theme prop (light default, dark per app theme) and renders
 * with react-native-svg. No CSS animations on native — the grammar's
 * motion register is a web-only layer.
 *
 * Run from the repo root:  node scripts/art/build-native.mjs
 */
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');
const SHARED = join(ROOT, 'shared', 'art');
const OUT = join(ROOT, 'apps', 'mobile', 'src', 'components', 'art');

/* ── 1. copy the pure art source ────────────────────────────────── */
rmSync(join(OUT, 'shared'), { recursive: true, force: true });
mkdirSync(join(OUT, 'shared', 'scenes'), { recursive: true });
cpSync(join(SHARED, 'grammar.ts'), join(OUT, 'shared', 'grammar.ts'));
cpSync(join(SHARED, 'manifest.ts'), join(OUT, 'shared', 'manifest.ts'));
for (const f of readdirSync(join(SHARED, 'scenes'))) {
  if (f.endsWith('.ts') && f !== 'stubs.ts') {
    cpSync(join(SHARED, 'scenes', f), join(OUT, 'shared', 'scenes', f));
  }
}

/* ── 2. the RN renderer ─────────────────────────────────────────── */
writeFileSync(join(OUT, 'RnArt.tsx'), `/**
 * RnArt — GENERATED by scripts/art/build-native.mjs (r359 A2).
 * Renders the shared art grammar (art/shared/) with react-native-svg.
 * Palette: concrete hex per theme (the web rides CSS custom
 * properties; native swaps them at render time).
 */
import React, { memo, useMemo } from 'react';
import Svg, { Circle, Ellipse, G, Line, Path, Polygon, Polyline, Rect, Text as SvgText } from 'react-native-svg';
import type { ArtBuilder, ArtDoc, ArtNode, ArtPlateProps } from './shared/grammar';

interface Pal {
  ink: string;
  ink2: string;
  hair: string;
  sig: string;
  paper: string;
}

const PALETTE: Record<'light' | 'dark', Pal> = {
  light: { ink: '#282828', ink2: '#62625F', hair: '#B3B3AF', sig: '#2540D9', paper: '#F3F2EC' },
  dark: { ink: '#F3F2EC', ink2: '#B3B3AF', hair: '#4A4A48', sig: '#8AA0FF', paper: '#1C1C1A' },
};

const CAMEL: Record<string, string> = {
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'stroke-dasharray': 'strokeDasharray',
  'stroke-opacity': 'strokeOpacity',
  'font-size': 'fontSize',
  'font-family': 'fontFamily',
  'font-weight': 'fontWeight',
  'text-anchor': 'textAnchor',
  'letter-spacing': 'letterSpacing',
  'dominant-baseline': 'dominantBaseline',
};

const FONT_MAP: Record<string, string> = {
  'var(--font-mono)': 'monospace',
  'var(--font-sans)': 'sans-serif',
};

function color(v: unknown, pal: Pal): unknown {
  if (typeof v !== 'string') return v;
  if (v === 'var(--r359-ink)') return pal.ink;
  if (v === 'var(--r359-ink-2)') return pal.ink2;
  if (v === 'var(--r359-hair)') return pal.hair;
  if (v === 'var(--r359-sig)') return pal.sig;
  if (v === 'var(--r359-paper)') return pal.paper;
  return FONT_MAP[v] ?? v;
}

function renderNode(n: ArtNode, i: React.Key, pal: Pal): React.JSX.Element {
  const raw = n.a ?? {};
  const p: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(raw)) {
    if (k === 'class' || k.startsWith('data-')) continue; // web-only hooks
    p[CAMEL[k] ?? k] = color(v, pal);
  }
  if (n.t === 'text') {
    return (
      <SvgText key={i} {...(p as object)}>
        {n.s}
      </SvgText>
    );
  }
  const T = n.t === 'g' ? G : n.t === 'path' ? Path : n.t === 'rect' ? Rect
    : n.t === 'circle' ? Circle : n.t === 'ellipse' ? Ellipse : n.t === 'line' ? Line
    : n.t === 'polyline' ? Polyline : Polygon;
  if (!n.c || n.c.length === 0) {
    return <T key={i} {...(p as object)} />;
  }
  return (
    <T key={i} {...(p as object)}>
      {n.c.map((c, j) => renderNode(c, j, pal))}
    </T>
  );
}

export interface RnArtProps extends ArtPlateProps {
  build: ArtBuilder;
}

function RnArtBase({ build, className, title, theme }: RnArtProps): React.JSX.Element {
  const doc: ArtDoc = useMemo(() => build(), [build]);
  const pal = theme === 'dark' ? PALETTE.dark : PALETTE.light;
  const t = title ?? doc.title;
  return (
    <Svg
      viewBox={\`0 0 \${doc.w} \${doc.h}\`}
      width="100%"
      height={undefined}
      accessibilityLabel={t}
      accessibilityRole="image"
      style={className ? undefined : { alignSelf: 'stretch' }}
    >
      {doc.nodes.map((n, i) => renderNode(n, i, pal))}
    </Svg>
  );
}

export const RnArt = memo(RnArtBase);
`);

/* ── 3. wrappers + index ────────────────────────────────────────── */
const FAMILIES = {
  hero: 'scenes/hero',
  plans: 'scenes/plans',
  sections: 'scenes/sections',
  why: 'scenes/sections',
  usecases: 'scenes/usecases',
  cta: 'scenes/sections',
  marks: 'scenes/states',
  states: 'scenes/states',
  onboarding: 'scenes/onboarding',
};
const STUB_FAMILY = {}; // keys still on stubs

const manifestSrc = readFileSync(join(SHARED, 'manifest.ts'), 'utf8');
const keyRe = /\{ key: '([^']+)', pascal: '([^']+)', title: '([^']+)', family: '([^']+)' \}/g;
const keys = [];
let m;
while ((m = keyRe.exec(manifestSrc)) !== null) {
  keys.push({ key: m[1], pascal: m[2], title: m[3], family: m[4] });
}

const exportsList = [];
for (const k of keys) {
  const mod = STUB_FAMILY[k.key] ?? FAMILIES[k.family];
  writeFileSync(join(OUT, `${k.pascal}.tsx`), `/**
 * ${k.pascal} — r359 art key \`${k.key}\` — ${k.title}
 * GENERATED by scripts/art/build-native.mjs (A2) — do not hand-edit.
 */
import { RnArt } from './RnArt';
import { sceneFor } from './shared/${mod}';

export interface R359ArtProps {
  className?: string;
  title?: string;
  animated?: boolean;
  theme?: 'light' | 'dark';
}

const BUILDER = sceneFor('${k.key}');

export default function ${k.pascal}(props: R359ArtProps): React.JSX.Element {
  return <RnArt build={BUILDER} {...props} />;
}
`);
  exportsList.push(`export { default as ${k.pascal} } from './${k.pascal}';`);
}

writeFileSync(
  join(OUT, 'index.ts'),
  `/**
 * apps/mobile/src/components/art — GENERATED by
 * scripts/art/build-native.mjs (r359 A2). One component per contract
 * key, all rendered from the shared art grammar (./shared/).
 */
${exportsList.join('\n')}
export { RnArt } from './RnArt';
export type { R359ArtProps } from './HeroElevation';
`,
);

console.log(`build-native: ${keys.length} components + shared source → ${OUT}`);
