#!/usr/bin/env node
/**
 * scripts/brand/build-app-icons.mjs — R327 B1 «الشعار الواحد».
 *
 * ONE canonical source: apps/mobile/src/brand/mark.ts (the 32-grid
 * ULARA U-vessel — the one ink stroke + the sienna cornerstone).
 * This script PARSES the
 * constants out of that file (loudly failing if its shape changes), builds
 * EVERY app asset from the same numbers, and byte-verifies the committed
 * PNGs/SVG in --check mode (wired into `npm run tokens:check` → CI).
 *
 * Assets (all from the one mark):
 *   apps/mobile/assets/images/icon.png             1024 — paper bg, punchy stroke
 *   apps/mobile/assets/images/adaptive-foreground  1024 — transparent, safe-zone scaled
 *   apps/mobile/assets/images/adaptive-background  1024 — solid paper
 *   apps/mobile/assets/images/adaptive-monochrome  1024 — all-white (Android 13+)
 *   apps/mobile/assets/images/splash-icon.png      1024 — transparent, hairline stroke
 *   apps/mobile/assets/images/favicon.png            48 — paper bg, favicon ratio
 *   apps/mobile/assets/images/notification-icon.png 96  — white silhouette (Android)
 *   shared/brand/mark.svg                          the ONE SVG (32 viewBox)
 *
 * Modes:
 *   (bare)  dry run — list committed assets and their hashes
 *   --png   rasterize + WRITE the assets (requires sharp — apps/mobile devDep)
 *   --check byte-compare regenerated bytes vs committed; exit 1 on drift
 *           (the CI gate — runs inside `npm run tokens:check`)
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const MARK_TS = join(ROOT, "apps", "mobile", "src", "brand", "mark.ts");
const IMG = join(ROOT, "apps", "mobile", "assets", "images");
const SHARED_BRAND = join(ROOT, "shared", "brand");

/* ── 1. the canonical geometry — parsed from mark.ts (never restated) ── */

const src = readFileSync(MARK_TS, "utf8");

function need(re, name, cast = (x) => x) {
  const m = re.exec(src);
  if (!m) {
    console.error(`build-app-icons: cannot find ${name} in mark.ts — the brand source changed shape; update the parser.`);
    process.exit(1);
  }
  return cast(m.slice(1));
}

const VIEWBOX = need(/MARK_VIEWBOX = '([^']+)'/, "MARK_VIEWBOX", (g) => g[0]);
const VESSEL = need(/MARK_VESSEL_PATH = '([^']+)'/, "MARK_VESSEL_PATH", (g) => g[0]);
const KEY = need(/MARK_CORNERSTONE = \{ x: (\d+), y: (\d+), size: (\d+) \}/, "MARK_CORNERSTONE", (g) => g.map(Number));

const STROKE_COMPONENT = 1.5; // mark.ts: hairline at the 32-grid design size
const STROKE_FAVICON = 2.25;  // mark.ts: the sanctioned small-seat ratio

/* ── 2. the one mark renderer (32-grid coordinates) ─────────────────── */

/**
 * Render the canonical mark as an SVG string.
 * stroke — stroke width in 32-viewBox units (proportional).
 * ink/orange — colours; canvas — output px; box — fraction of the canvas
 * the full 32-grid box occupies; bg — background fill or null.
 */
function markSvg({ stroke, ink = "#262019", orange = "#C43E16", canvas = 1024, box = 1, bg = null }) {
  // Build in the mark's own 32-unit space; the viewBox carries the box
  // fraction (the mark occupies `box` of the canvas, centred) so the path
  // commands stay literal — never re-scale path numbers by hand.
  const vb = 32 / box; // total viewBox units across the canvas
  const off = +((vb - 32) / 2).toFixed(4);
  const bgRect = bg ? `<rect x="${-off}" y="${-off}" width="${vb}" height="${vb}" fill="${bg}"/>` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${canvas}" height="${canvas}" viewBox="${-off} ${-off} ${vb} ${vb}">${bgRect}<g fill="none" stroke="${ink}" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round"><path d="${VESSEL}"/></g><rect x="${KEY[0]}" y="${KEY[1]}" width="${KEY[2]}" height="${KEY[2]}" fill="${orange}"/></svg>`;
}

/* ── 3. the asset table (every number derived from the one source) ──── */

const PAPER = "#F5F1E8";
const ASSETS = {
  // App icon — punchy favicon-ratio strokes on paper.
  "icon.png": { svg: () => markSvg({ stroke: STROKE_FAVICON, bg: PAPER, box: 0.74 }) },
  // Android adaptive — foreground inside the ~55% safe zone, transparent.
  "adaptive-foreground.png": { svg: () => markSvg({ stroke: STROKE_FAVICON, box: 0.55 }) },
  "adaptive-background.png": { svg: () => markSvg({ stroke: STROKE_FAVICON, ink: "#FFFFFF", orange: "#FFFFFF", bg: PAPER }) },
  "adaptive-monochrome.png": { svg: () => markSvg({ stroke: STROKE_FAVICON, ink: "#FFFFFF", orange: "#FFFFFF", box: 0.55 }) },
  // Splash — the hairline construction exactly as the in-app <Logo>.
  "splash-icon.png": { svg: () => markSvg({ stroke: STROKE_COMPONENT, box: 0.8 }) },
  // Web favicon 48 — paper bg, favicon ratio.
  "favicon.png": { svg: () => markSvg({ stroke: STROKE_FAVICON, bg: PAPER, box: 0.86, canvas: 48 }) },
  // Android status-bar silhouette (white-only, transparent).
  "notification-icon.png": { svg: () => markSvg({ stroke: STROKE_FAVICON, ink: "#FFFFFF", orange: "#FFFFFF", box: 0.8, canvas: 96 }) },
};

/* ── 4. modes ────────────────────────────────────────────────────────── */

const MODE = process.argv.includes("--check") ? "check" : process.argv.includes("--png") ? "png" : "dry";
const sha = (b) => createHash("sha256").update(b).digest("hex").slice(0, 16);

/* R327 D2/Z14: sharp is a devDependency of apps/mobile — resolve it from
 * THERE. A bare import("sharp") from this script's location walked up to
 * the AMBIENT node_modules (this sandbox's /home/z/node_modules happened
 * to have sharp — CI and any fresh clone do not, which kept the Mobile
 * workflow red since B1). */
const mobileRequire = createRequire(
  new URL("../../apps/mobile/package.json", import.meta.url),
);

let sharpMod = null;
async function rasterize(svgString) {
  if (!sharpMod) {
    try {
      sharpMod = mobileRequire("sharp");
    } catch {
      console.error("build-app-icons: sharp is not installed — run `npm ci` in apps/mobile (devDependency).");
      process.exit(1);
    }
  }
  return sharpMod(Buffer.from(svgString)).png({ compressionLevel: 9 }).toBuffer();
}

mkdirSync(SHARED_BRAND, { recursive: true });

let drift = 0;
const report = (name, ok, note) => {
  console.log(`  ${ok ? "✔" : "✖"} ${name}${note ? ` — ${note}` : ""}`);
  if (!ok) drift++;
};

console.log(`build-app-icons (${MODE}) — source: apps/mobile/src/brand/mark.ts`);

// The ONE SVG — canonical, committed, byte-checked (viewBox = mark's own).
const oneSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="${VIEWBOX}"><g fill="none" stroke="#262019" stroke-width="${STROKE_COMPONENT}" stroke-linecap="round" stroke-linejoin="round"><path d="${VESSEL}"/></g><rect x="${KEY[0]}" y="${KEY[1]}" width="${KEY[2]}" height="${KEY[2]}" fill="#C43E16"/></svg>`;

if (MODE === "png") {
  writeFileSync(join(SHARED_BRAND, "mark.svg"), oneSvg + "\n");
  report("shared/brand/mark.svg", true, "written");
  for (const [name, { svg }] of Object.entries(ASSETS)) {
    const png = await rasterize(svg());
    writeFileSync(join(IMG, name), png);
    report(name, true, `written (${png.length} bytes, sha ${sha(png)})`);
  }
  process.exit(drift ? 1 : 0);
}

// dry / check — compare the one SVG against the committed copy
let committedOneSvg = null;
try {
  committedOneSvg = readFileSync(join(SHARED_BRAND, "mark.svg"), "utf8");
} catch {
  /* missing — reported below */
}
report("shared/brand/mark.svg", committedOneSvg === oneSvg + "\n", committedOneSvg === oneSvg + "\n" ? "byte-identical" : "DRIFT — run: npm run icons");

if (MODE === "dry") {
  for (const name of Object.keys(ASSETS)) {
    try {
      const b = readFileSync(join(IMG, name));
      console.log(`  · ${name} — committed ${b.length} bytes (sha ${sha(b)}) — run with --png to regenerate from mark.ts`);
    } catch {
      console.log(`  · ${name} — MISSING`);
      drift++;
    }
  }
  process.exit(drift ? 1 : 0);
}

// check — regenerate in memory and byte-compare every committed asset
for (const [name, { svg }] of Object.entries(ASSETS)) {
  const png = await rasterize(svg());
  let committed = null;
  try {
    committed = readFileSync(join(IMG, name));
  } catch {
    report(name, false, "committed file MISSING");
    continue;
  }
  const same = Buffer.compare(png, committed) === 0;
  report(name, same, same ? `sha ${sha(png)}` : `DRIFT (committed sha ${sha(committed)}, regen sha ${sha(png)}) — run: npm run icons`);
}

if (drift) {
  console.error(`build-app-icons: ${drift} asset(s) drifted from apps/mobile/src/brand/mark.ts — regenerate with \`npm run icons\` (apps/mobile) and commit.`);
  process.exit(1);
}
console.log("build-app-icons: every asset byte-identical to the one mark. ✔");
