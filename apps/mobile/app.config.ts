/* ── R336 F — the scoped cleartext network-security config ──────────────
 *
 * RN's gradle plugin pins `usesCleartextTraffic=false` for RELEASE builds
 * (AgpConfiguratorUtils.kt), so Android blocks the android-smoke lane's
 * `http://10.0.2.2:4000/api/v1` local backend outright — the login POST
 * fails with the Arabic NETWORK error ("تعذّر الاتصال بالخادم…") and the
 * five-role journey can never pass (root-caused from the run-43412249079
 * forensics: the submit tap landed, the app stayed on the login form with
 * the network error visible; logcat clean — no crash).
 *
 * The fix is the Android-standard SCOPED network security config: cleartext
 * is permitted ONLY to the emulator-host loopback aliases (10.0.2.2 = the
 * AVD host loopback, 10.0.3.2 = Genymotion, localhost = adb-reverse dev
 * builds); every other destination stays https-only (base-config false).
 * No production surface is on those addresses — production keeps its
 * strict default; the local-backend emulator lane becomes reachable.
 * On API 24+ the NSC takes precedence over usesCleartextTraffic, so debug
 * builds keep working via the loopback entries (Metro/adb-reverse).
 */
const NETWORK_SECURITY_CONFIG_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- R336 F — scoped cleartext: emulator-host loopback ONLY (android-smoke's
     local backend at http://10.0.2.2:4000; adb-reverse dev on localhost).
     Everything else stays https-only. Generated by app.config.ts — do not
     hand-edit (the file lives in the prebuild output, not the repo). -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">10.0.2.2</domain>
        <domain includeSubdomains="false">10.0.3.2</domain>
        <domain includeSubdomains="false">localhost</domain>
    </domain-config>
</network-security-config>
`;

const withLoopbackCleartext: ConfigPlugin = (config) => {
  let cfg = withAndroidManifest(config, (c) => {
    const application = c.modResults.manifest.application?.[0];
    if (application) {
      application.$ = { ...application.$, "android:networkSecurityConfig": "@xml/network_security_config" };
    }
    return c;
  });
  cfg = withDangerousMod(cfg, [
    "android",
    (c) => {
      const resDir = path.join(
        c.modRequest.projectRoot,
        "android",
        "app",
        "src",
        "main",
        "res",
        "xml",
      );
      fs.mkdirSync(resDir, { recursive: true });
      fs.writeFileSync(path.join(resDir, "network_security_config.xml"), NETWORK_SECURITY_CONFIG_XML);
      return c;
    },
  ]);
  return cfg;
};

